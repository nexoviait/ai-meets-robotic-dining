/**
 * Equirectangular projection for the offline district map (DistrictSchematicMap), used when
 * Google Maps cannot load. Longitudes are scaled by cos(23.7°) so Bangladesh keeps its shape.
 */
const LON0 = 87.9;
const LON1 = 92.8;
const LAT0 = 20.5;
const LAT1 = 26.75;
const K = Math.cos((23.7 * Math.PI) / 180);

export const MAP_WIDTH = 1000;
export const MAP_HEIGHT = Math.round((MAP_WIDTH * (LAT1 - LAT0)) / ((LON1 - LON0) * K));

/** Projects a coordinate into the map's SVG viewBox (0 0 MAP_WIDTH MAP_HEIGHT). */
export function projectToMap(lat: number, lng: number) {
  return {
    x: ((lng - LON0) / (LON1 - LON0)) * MAP_WIDTH,
    y: ((LAT1 - lat) / (LAT1 - LAT0)) * ((MAP_WIDTH * (LAT1 - LAT0)) / ((LON1 - LON0) * K)),
  };
}

